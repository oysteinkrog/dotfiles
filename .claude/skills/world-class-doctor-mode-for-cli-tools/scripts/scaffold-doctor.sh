#!/usr/bin/env bash
set -euo pipefail

# scaffold-doctor.sh — emit a stub doctor module for a target language.
#
# Phase 4 implementer agents currently start from a blank file per language.
# This script writes a compilable starter module with the canonical 10
# subcommands stubbed, the mutate() chokepoint declared, and the JSON output
# shape pre-wired so implementers fill in detector/fixer bodies, not plumbing.
#
# Usage:
#   scaffold-doctor.sh --target <dir> --tool <name> [--language <lang>] [--out <path>]
#
# Args:
#   --target <dir>    — target project root. Required.
#   --tool <name>     — binary name (used in CLI parser). Required.
#   --language <lang> — one of: rust|go|python|typescript. If omitted, auto-detect
#                       via discover-cli.sh.
#   --out <path>      — output file path. Default: <target>/<canonical-doctor-path>.
#                       Refuses to overwrite an existing file unless --force.
#   --force           — overwrite an existing file at --out.
#
# Exit codes: 0 on success, 64 usage, 66 target/lang not supported, 73 cant-create.
#
# This emits a SKELETON that compiles. Filling in detector/fixer bodies is
# Phase 4 work; the structural pieces (mutate chokepoint, exit codes, JSON
# shape, subcommand dispatch) are all done.

usage() {
    cat <<'USAGE_EOF' >&2
usage: scaffold-doctor.sh --target <dir> --tool <name> [--language <lang>] [--out <path>] [--force]
  --target   project root (required)
  --tool     binary/tool name (required)
  --language rust|go|python|typescript (auto-detected if omitted)
  --out      output file path (default: language-specific canonical location)
  --force    overwrite existing output
USAGE_EOF
}

target=""
tool=""
language=""
out_path=""
force=0
need_value() {
    [ -n "${2:-}" ] || { echo "scaffold-doctor: $1 requires a value" >&2; usage; exit 64; }
    case "$2" in --*) echo "scaffold-doctor: $1 requires a value, got option-like token: $2" >&2; usage; exit 64 ;; esac
}

while [ $# -gt 0 ]; do
    case "$1" in
        --target) need_value "$1" "${2:-}"; target="$2"; shift 2 ;;
        --tool)   need_value "$1" "${2:-}"; tool="$2"; shift 2 ;;
        --language) need_value "$1" "${2:-}"; language="$2"; shift 2 ;;
        --out)    need_value "$1" "${2:-}"; out_path="$2"; shift 2 ;;
        --force)  force=1; shift ;;
        -h|--help) usage; exit 0 ;;
        *) echo "scaffold-doctor: unknown arg $1" >&2; usage; exit 64 ;;
    esac
done

if [ -z "$target" ] || [ -z "$tool" ]; then
    usage; exit 64
fi
[ -d "$target" ] || { echo "scaffold-doctor: $target not a directory" >&2; exit 66; }

# Auto-detect language if not specified.
if [ -z "$language" ]; then
    SKILL_DIR="$(cd "$(dirname "$0")/.." && pwd)"
    detect_json=$("$SKILL_DIR/scripts/discover-cli.sh" "$target" 2>/dev/null) || true
    language=$(printf '%s' "$detect_json" | python3 -c 'import json,sys
try:
    print(json.loads(sys.stdin.read()).get("language", ""))
except Exception:
    pass' 2>/dev/null || true)
fi

case "$language" in
    rust|go|python|typescript) ;;
    *)
        echo "scaffold-doctor: unsupported or undetected language '$language'" >&2
        echo "  supported: rust|go|python|typescript" >&2
        exit 66
        ;;
esac

# Determine canonical output path per language if not specified.
if [ -z "$out_path" ]; then
    case "$language" in
        rust)       out_path="$target/src/doctor.rs" ;;
        go)         out_path="$target/internal/doctor/doctor.go" ;;
        python)     out_path="$target/src/$(echo "$tool" | tr - _)/doctor.py" ;;
        typescript) out_path="$target/src/doctor.ts" ;;
    esac
fi

if [ -e "$out_path" ] && [ "$force" -ne 1 ]; then
    echo "scaffold-doctor: refusing to overwrite existing $out_path (use --force)" >&2
    exit 73
fi

# Ensure parent directory exists.
mkdir -p "$(dirname "$out_path")" \
    || { echo "scaffold-doctor: cant_create $(dirname "$out_path")" >&2; exit 73; }

