/// Top-level dispatch. Argument parsing should pin to clap; this is a stub.
pub fn run_doctor(args: Vec<String>) -> ExitCode {
    let subcommand = args.first().map(|s| s.as_str()).unwrap_or("diagnose");
    let rest = args.get(1..).unwrap_or(&[]);
    match subcommand {
        "diagnose" | "" => diagnose(rest),
        "fix" => fix(rest),
        "undo" => undo(rest),
        "explain" => explain(rest),
        "capabilities" => capabilities(rest),
        "health" => health(rest),
        "robot-docs" => robot_docs(rest),
        "gc" => gc(rest),
        "ls" => ls(rest),
        "diff" => diff(rest),
        _ => {
            eprintln!("$tool doctor: unknown subcommand '{}'", subcommand);
            ExitCode::from(exit::USAGE_ERROR)
        }
    }
}

