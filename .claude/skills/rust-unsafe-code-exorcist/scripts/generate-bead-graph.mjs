#!/usr/bin/env node
// generate-bead-graph.mjs — convert audit plans into a br-create script
// Usage: node generate-bead-graph.mjs <audit-dir>

import fs from 'node:fs';
import path from 'node:path';

const auditDirArg = process.argv[2];
if (!auditDirArg) {
  console.error('usage: generate-bead-graph.mjs <audit-dir>');
  process.exit(1);
}
const AUDIT_DIR = realpath(auditDirArg);
assertAuditDirInsideProject(AUDIT_DIR, inferProjectRoot(AUDIT_DIR));

const synthesisFile = path.join(AUDIT_DIR, 'audit/synthesis/refactor-clusters.md');
const classDir = path.join(AUDIT_DIR, 'audit/classification');
const plansDir = path.join(AUDIT_DIR, 'audit/plans');
const preExisting = path.join(AUDIT_DIR, 'audit/synthesis/pre-existing-ub.md');

const out = path.join(AUDIT_DIR, 'phase8_bead_commands.sh');

// Parse clusters from synthesis. Loose match by `## Cluster X-NNN: <title>` headers.
let clusters = [];
if (fs.existsSync(synthesisFile)) {
  const content = fs.readFileSync(synthesisFile, 'utf8');
  const clusterRe = /^## Cluster (\S+): (.+)$/gm;
  let m;
  while ((m = clusterRe.exec(content))) {
    clusters.push({ name: m[1], title: m[2], sites: [] });
  }
}

// Walk classification files; assign to bucket
const classFiles = fs.existsSync(classDir)
  ? fs.readdirSync(classDir).filter(f => /^site-\d+\.md$/.test(f))
  : [];

// Cluster field in the classification template lives on a "**Cluster.** `<name>`" line
// (per assets/classification-template.md). We accept that shape AND the legacy
// "Cluster: <name>" / "Cluster: `<name>`" shapes for robustness.
const CLUSTER_RE = /^\*\*Cluster\.\*\*\s+`?([^`\s][^`\n]*?)`?\s*$/m;
const CLUSTER_RE_LEGACY = /^Cluster:\s+`?([^`\s][^`\n]*?)`?\s*$/m;

const sites = classFiles.map(f => {
  const content = fs.readFileSync(path.join(classDir, f), 'utf8');
  const bucketMatch = content.match(/^#\s+(site-\d+)\s+—\s+\((A|B|C)\)/m);
  const bucketFieldMatch = content.match(/\*\*Bucket\.\*\*\s+`?\(([ABC])\)/);
  const clusterMatch = content.match(CLUSTER_RE) ?? content.match(CLUSTER_RE_LEGACY);
  const id = bucketMatch?.[1] ?? f.replace(/\.md$/, '');
  let cluster = clusterMatch?.[1]?.trim() ?? null;
  // Reject placeholder / orphan sentinels.
  if (cluster && /^(orphan|none|n\/a|<[^>]*>)$/i.test(cluster)) cluster = null;
  return {
    id,
    bucket: bucketMatch?.[2] ?? bucketFieldMatch?.[1] ?? 'C',
    cluster,
    planPath: path.join('audit/plans', `${id}.md`),
  };
});

// Group sites into clusters; orphan sites form an `unclustered` group
for (const s of sites) {
  if (s.cluster) {
    const c = clusters.find(c => c.name === s.cluster);
    if (c) c.sites.push(s);
    else clusters.push({ name: s.cluster, title: s.cluster, sites: [s] });
  }
}
const orphans = sites.filter(s => !s.cluster);

// Pre-existing UB beads
const peuBs = [];
if (fs.existsSync(preExisting)) {
  const content = fs.readFileSync(preExisting, 'utf8');
  const peuRe = /^## pre-existing-ub-(\d+):/gm;
  let m;
  while ((m = peuRe.exec(content))) {
    peuBs.push({ id: `pre-existing-ub-${m[1]}` });
  }
}

// Emit the bash script
const lines = [
  '#!/usr/bin/env bash',
  '# Generated by generate-bead-graph.mjs — Phase 8 bead conversion',
  'set -euo pipefail',
  '',
  `cd ${shellQuote(AUDIT_DIR)}`,
  '',
];
const usedShellIdentifiers = new Set();

for (const cluster of clusters) {
  const epicVar = shellIdentifier('EPIC', cluster.name);
  lines.push(`# === Epic: ${cluster.title} ===`);
  lines.push(`${epicVar}=$(br create --title ${shellQuote(`[${cluster.name}] ${cluster.title}`)} \\`);
  lines.push(`    --type epic --priority 1 \\`);
  lines.push(`    --description ${shellQuote(`Cluster ${cluster.name}. See audit/synthesis/refactor-clusters.md`)} \\`);
  lines.push(`    --json | jq -r '.id')`);
  lines.push('');

  for (const s of cluster.sites) {
    const siteVar = shellIdentifier('S', s.id);
    const bead = beadShapeForSite(s);
    lines.push(`${siteVar}=$(br create --title ${shellQuote(`[${cluster.name} / ${s.id}] ${bead.title}`)} \\`);
    lines.push(`    --type ${bead.type} --priority ${bead.priority} \\`);
    lines.push(`    --description ${shellQuote(`${bead.description} See ${s.planPath}`)} \\`);
    lines.push(`    --json | jq -r '.id')`);
    lines.push(`# Parent epic is blocked until the site bead is done; the site bead stays ready.`);
    lines.push(`br dep add $${epicVar} $${siteVar}`);
    lines.push('');
  }
}

if (orphans.length > 0) {
  lines.push('# === Orphan sites (no cluster) ===');
  for (const s of orphans) {
    const siteVar = shellIdentifier('S', s.id);
    const bead = beadShapeForSite(s);
    lines.push(`${siteVar}=$(br create --title ${shellQuote(`[orphan / ${s.id}] ${bead.title}`)} \\`);
    lines.push(`    --type ${bead.type} --priority ${bead.priority} \\`);
    lines.push(`    --description ${shellQuote(`${bead.description} See ${s.planPath}`)} \\`);
    lines.push(`    --json | jq -r '.id')`);
    lines.push('');
  }
}

if (peuBs.length > 0) {
  lines.push('# === Pre-existing UB beads (NOT IN REFACTOR SCOPE) ===');
  for (const p of peuBs) {
    lines.push(`br create --title ${shellQuote(`${p.id} [NOT IN REFACTOR SCOPE]`)} \\`);
    lines.push(`    --type bug --priority 0 \\`);
    lines.push(`    --description ${shellQuote(`See audit/synthesis/pre-existing-ub.md § ${p.id}`)}`);
    lines.push('');
  }
}

lines.push('br sync --flush-only');
lines.push(`echo ${shellQuote('Bead graph created. Run "br ready" to see unblocked work.')}`);

fs.writeFileSync(out, lines.join('\n') + '\n');
fs.chmodSync(out, 0o755);

console.log(`Wrote ${out}`);
console.log(`Clusters: ${clusters.length}; sites: ${sites.length}; pre-existing-ub: ${peuBs.length}`);

function inferProjectRoot(auditDir) {
  const marker = path.join(auditDir, 'phase1', 'project-root.txt');
  if (fs.existsSync(marker)) {
    const recorded = fs.readFileSync(marker, 'utf8').trim();
    if (recorded) return recorded;
  }
  let cur = path.dirname(auditDir);
  while (true) {
    if (fs.existsSync(path.join(cur, 'Cargo.toml'))) return cur;
    const parent = path.dirname(cur);
    if (parent === cur) return null;
    cur = parent;
  }
}

function realpath(filePath) {
  return fs.realpathSync(path.resolve(filePath));
}

function assertAuditDirInsideProject(auditDir, projectRoot) {
  if (!projectRoot) {
    console.error(`error: cannot infer audited project root from audit dir: ${auditDir}`);
    process.exit(2);
  }
  const auditReal = realpath(auditDir);
  const projectReal = realpath(projectRoot);
  if (auditReal === projectReal) {
    console.error('error: audit dir must be a child directory inside the project, not the project root');
    process.exit(2);
  }
  const relative = path.relative(projectReal, auditReal);
  if (relative.startsWith('..') || path.isAbsolute(relative)) {
    console.error('error: audit dir must live inside the project being audited');
    console.error(`       project:   ${projectReal}`);
    console.error(`       audit dir: ${auditReal}`);
    process.exit(2);
  }
}

function shellIdentifier(prefix, value) {
  const stem = String(value)
    .toUpperCase()
    .replace(/[^A-Z0-9_]/g, '_')
    .replace(/^_+|_+$/g, '') || 'ITEM';
  let candidate = `${prefix}_${stem}`;
  let suffix = 2;
  while (usedShellIdentifiers.has(candidate)) {
    candidate = `${prefix}_${stem}_${suffix}`;
    suffix += 1;
  }
  usedShellIdentifiers.add(candidate);
  return candidate;
}

function shellQuote(value) {
  return "'" + String(value).replace(/'/g, "'\\''") + "'";
}

function beadShapeForSite(site) {
  if (site.bucket === 'A') {
    return {
      type: 'task',
      priority: 0,
      title: `(${site.bucket}) harden SAFETY proof`,
      description: 'Unavoidable unsafe: strengthen comments, invariants, and proof-obligation checks.',
    };
  }
  if (site.bucket === 'B') {
    return {
      type: 'feature',
      priority: 3,
      title: `(${site.bucket}) safe-only feature and CI guardrail`,
      description: 'Perf-only unsafe: keep the optimized path while proving the safe-only fallback and CI matrix.',
    };
  }
  return {
    type: 'task',
    priority: 1,
    title: `(${site.bucket}) refactor unsafe away`,
    description: 'Refactorable unsafe: implement the safe replacement and equivalence tests.',
  };
}
