#!/usr/bin/env node
// compute-risk-score.mjs — compute RISK_SCORE per site; emit risk-summary.md.
// Per RISK-SCORING.md.
//
// Usage: node compute-risk-score.mjs <audit-dir>

import fs from 'node:fs';
import path from 'node:path';

const auditDirArg = process.argv[2];
if (!auditDirArg) {
  console.error('usage: compute-risk-score.mjs <audit-dir>');
  process.exit(1);
}
const AUDIT_DIR = realpath(auditDirArg);
assertAuditDirInsideProject(AUDIT_DIR, inferProjectRoot(AUDIT_DIR));

const invPath = path.join(AUDIT_DIR, 'unsafe-inventory.jsonl');
const classDir = path.join(AUDIT_DIR, 'audit/classification');
const outDir = path.join(AUDIT_DIR, 'audit/synthesis');
const outFile = path.join(outDir, 'risk-summary.md');
const outJson = path.join(AUDIT_DIR, 'risk-scores.json');

fs.mkdirSync(outDir, { recursive: true });

// Parse inventory
if (!fs.existsSync(invPath)) {
  console.error(`error: ${invPath} not found`);
  process.exit(1);
}

const sites = fs.readFileSync(invPath, 'utf8')
  .split('\n').filter(Boolean).map(JSON.parse);

// Compute per-site scores (heuristic; refine per project)
const scored = sites.map(site => {
  // BLAST_RADIUS — best-effort from public-api flag + dep count (we don't have crates.io
  // reverse-deps in offline mode; default to 2 for pub items, 1 otherwise).
  let blast = site.public_api_exposed ? 2 : 1;
  if (site.ffi) blast = Math.max(blast, 3);    // FFI surfaces often inherit downstream risk
  if (site.intrinsic) blast = Math.max(blast, 2);

  // LIKELIHOOD — heuristic from macro-origin (inherits soundness; lower) + ubs findings.
  let likelihood = 3;  // default: unknown
  if (site.macro_origin) likelihood = 2;  // macro-inherited soundness
  if (Array.isArray(site.ubs_findings) && site.ubs_findings.length > 0) likelihood = 5;

  // DISCOVERABILITY — heuristic from public-api + kind.
  let discoverability = 1;
  if (site.public_api_exposed) {
    discoverability = 3;
    // Bump if the enclosing fn takes &[u8] / &str (heuristic via source_excerpt).
    if (site.source_excerpt && /&\s*\[u8\]|&str/.test(site.source_excerpt)) {
      discoverability = 4;
    }
  }
  if (site.kind === 'extern_block' || site.kind === 'asm') discoverability = Math.max(discoverability, 3);

  const score = blast * likelihood * discoverability;
  const bucket = score >= 60 ? 'P0' : score >= 25 ? 'P1' : score >= 10 ? 'P2' : 'P3';

  // Bucket-aware classification lookup
  const classFile = path.join(classDir, `${site.id}.md`);
  let classBucket = '?';
  if (fs.existsSync(classFile)) {
    const txt = fs.readFileSync(classFile, 'utf8');
    classBucket = parseClassificationBucket(txt) ?? '?';
  }

  return {
    id: site.id,
    crate: site.crate,
    file: site.file,
    line_start: site.line_start,
    kind: site.kind,
    public_api_exposed: site.public_api_exposed,
    blast,
    likelihood,
    discoverability,
    score,
    bucket,
    class_bucket: classBucket,
  };
});

// Sort by score desc
scored.sort((a, b) => b.score - a.score);

// Save JSON
fs.writeFileSync(outJson, JSON.stringify(scored, null, 2));

// Aggregate
const total = scored.reduce((s, x) => s + x.score, 0);
const p0 = scored.filter(x => x.bucket === 'P0');
const p1 = scored.filter(x => x.bucket === 'P1');
const p2 = scored.filter(x => x.bucket === 'P2');
const p3 = scored.filter(x => x.bucket === 'P3');

const cumulative = (top_n) => {
  const sum_top = scored.slice(0, top_n).reduce((s, x) => s + x.score, 0);
  return total > 0 ? (sum_top / total * 100).toFixed(1) : '0';
};

const lines = [
  '# Risk-Score Summary',
  '',
  `Generated by compute-risk-score.mjs on ${new Date().toISOString()}.`,
  `Total sites scored: ${scored.length}`,
  `Aggregate project risk (sum of scores): ${total}`,
  '',
  '## Distribution',
  '',
  '| Score range | Bucket | Count | Cumulative risk % |',
  '|-------------|--------|-------|-------------------|',
  `| 60-125 | P0 critical | ${p0.length} | ${cumulative(p0.length)}% |`,
  `| 25-59  | P1 high     | ${p1.length} | ${cumulative(p0.length + p1.length)}% |`,
  `| 10-24  | P2 medium   | ${p2.length} | ${cumulative(p0.length + p1.length + p2.length)}% |`,
  `| 1-9    | P3 low      | ${p3.length} | 100% |`,
  '',
  '## Cumulative coverage',
  '',
];
for (const n of [5, 10, 20, 50]) {
  if (scored.length >= n) {
    lines.push(`- Top ${n} sites cover **${cumulative(n)}%** of total risk-points.`);
  }
}
lines.push('');
lines.push('## Recommendation');
lines.push('');
// Find smallest top-N covering >=80% cumulative risk. findIndex returns -1 if
// no element matches; in that case the whole list is the recommended batch.
const pareto_idx = scored.findIndex((_, i) => parseFloat(cumulative(i + 1)) >= 80);
const top_n_pareto = pareto_idx === -1 ? scored.length : pareto_idx + 1;
lines.push(`Maximum-leverage refactor batch: **top ${top_n_pareto} sites** (covers ${cumulative(top_n_pareto)}% of risk).`);
lines.push('');
lines.push('## Top 20 sites');
lines.push('');
lines.push('| Site | Class | BR | LK | DC | Score | Bucket | File |');
lines.push('|------|-------|----|----|----|-------|--------|------|');
for (const s of scored.slice(0, 20)) {
  lines.push(`| ${s.id} | (${s.class_bucket}) | ${s.blast} | ${s.likelihood} | ${s.discoverability} | ${s.score} | ${s.bucket} | \`${s.file}:${s.line_start}\` |`);
}
lines.push('');
lines.push('---');
lines.push('');
lines.push('## Notes');
lines.push('');
lines.push('- Scores are HEURISTIC. Calibrate per [risk-score-rubric.md](../../assets/risk-score-rubric.md).');
lines.push('- Per-project rubric overrides go in `<audit-dir>/risk-rubric-override.md` (not yet present).');
lines.push('- BR = BLAST_RADIUS; LK = LIKELIHOOD; DC = DISCOVERABILITY.');

fs.writeFileSync(outFile, lines.join('\n') + '\n');

console.log(`Risk-scored ${scored.length} sites.`);
console.log(`  P0 (60-125): ${p0.length}`);
console.log(`  P1 (25-59):  ${p1.length}`);
console.log(`  P2 (10-24):  ${p2.length}`);
console.log(`  P3 (1-9):    ${p3.length}`);
console.log(`Total project risk: ${total}`);
console.log(`Wrote ${outFile}`);

function inferProjectRoot(auditDir) {
  const marker = path.join(auditDir, 'phase1', 'project-root.txt');
  if (fs.existsSync(marker)) {
    const recorded = fs.readFileSync(marker, 'utf8').trim();
    if (recorded) return recorded;
  }
  let cur = path.dirname(auditDir);
  while (true) {
    if (fs.existsSync(path.join(cur, 'Cargo.toml'))) return cur;
    const parent = path.dirname(cur);
    if (parent === cur) return null;
    cur = parent;
  }
}

function realpath(filePath) {
  return fs.realpathSync(path.resolve(filePath));
}

function assertAuditDirInsideProject(auditDir, projectRoot) {
  if (!projectRoot) {
    console.error(`error: cannot infer audited project root from audit dir: ${auditDir}`);
    process.exit(2);
  }
  const auditReal = realpath(auditDir);
  const projectReal = realpath(projectRoot);
  if (auditReal === projectReal) {
    console.error('error: audit dir must be a child directory inside the project, not the project root');
    process.exit(2);
  }
  const relative = path.relative(projectReal, auditReal);
  if (relative.startsWith('..') || path.isAbsolute(relative)) {
    console.error('error: audit dir must live inside the project being audited');
    console.error(`       project:   ${projectReal}`);
    console.error(`       audit dir: ${auditReal}`);
    process.exit(2);
  }
}

function parseClassificationBucket(text) {
  const fieldMatch = text.match(/\*\*Bucket\.\*\*\s+`?\(([ABC])\)/);
  if (fieldMatch) return fieldMatch[1];
  const headingMatch = text.match(/^#\s+site-\d+\s+—\s+\(([ABC])\)/m);
  return headingMatch?.[1] ?? null;
}
console.log(`Wrote ${outJson}`);
